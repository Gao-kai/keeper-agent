r"""
## Reciprocal Rank Fusion（倒数排名融合）算法详解

### 一句话概括

RRF 是一种**基于排名位置**（而非原始分数）的多路检索结果融合算法，通过对每个文档在各路召回中的排名取倒数并求和，来生成最终的综合排序。

---

### 核心公式

$$RRF\_Score(d) = \sum_{i=1}^{N} \frac{1}{k + rank_i(d)}$$

其中：

- **N**：参与融合的检索路数（如 BM25、向量检索等）
- **rank_i(d)**：文档 d 在第 i 路检索结果中的排名（从 1 开始）
- **k**：平滑常数，通常取 **60**（由原始论文建议）
- 若文档 d 未出现在某路结果中，则该项贡献为 0

---

### 核心思想

RRF 的核心思想是：**不比较不同检索方式的原始分数，只比较排名位置**。

这解决了混合检索中的一个关键难题
不同检索器的分数尺度完全不同（例如 BM25 分数无上界，向量余弦相似度在 [-1, 1] 之间），很难归一化到同一量纲。
RRF 直接绕过了这个问题。

**举个具体例子**：假设用全文检索和向量检索同时搜索"舒适的自行车座椅"：

| 排名 | 全文检索结果 | 向量检索结果 |
|------|------------|------------|
| 1 | 自行车座椅舒适专家版 | 人体工学旅行鞍 |
| 2 | 舒适的车把套 | 凝胶垫鞍 |
| 3 | 赛车座椅 | 自行车座椅舒适专家版 |

"自行车座椅舒适专家版"在全文检索排第 1、向量检索排第 3，RRF 分数为：
- 全文排名 1：1/(60+1) = 0.0164
- 向量排名 3：1/(60+3) = 0.0159
- **综合：0.0323**

而"人体工学旅行鞍"仅在向量检索排第 1：
- 向量排名 1：1/(60+1) = 0.0164
- **综合：0.0164**

尽管"人体工学旅行鞍"在向量检索中排名第一，但"自行车座椅舒适专家版"因为在**两个列表中都排名靠前**，综合得分翻倍，最终排在融合结果的第一位。

---

### 算法执行步骤

1. **多路并行检索**：各检索器（BM25、向量检索等）独立返回排序列表
2. **记录排名**：对每个文档，记录它在每路结果中的排名位置
3. **计算 RRF 分数**：对每个文档，将所有路中 `1/(k + rank)` 的值求和
4. **重新排序**：按 RRF 分数从高到低排序，得到最终融合结果

---

### 参数 k 的作用

| k 值大小 | 效果 |
|---------|------|
| **较小**（如 5~20） | 更强调头部排名，排名靠前的文档得分优势更大 |
| **较大**（如 60~100） | 分数分布更平滑，中低排名文档也能获得一定贡献 |
| **默认 60** | 原始论文推荐的零样本默认值，在多数场景下表现良好 |

需要注意的是，k 并非"设了就忘"的参数——研究表明 RRF 对 k 值较为敏感，不同领域可能需要通过网格搜索来找到最优值。

---

### 优势

- **无需分数归一化**：只依赖排名，天然适配不同评分体系的检索器
- **零样本可用**：不需要标注数据或训练，开箱即用
- **鲁棒性强**：单一检索器的异常高分不会主导最终结果，促进"共识"
- **实现简单**：计算开销低，易于集成到现有检索管道中



---

### 局限性

- **丢弃了分数信息**：仅使用排名位置，忽略了原始分数的差距信息（如第 1 名和第 2 名的分差可能很大，但 RRF 无法体现）
- **k 值敏感**：默认 k=60 并非所有场景最优，跨域迁移性较差
- **延迟增加**：需要多路并行检索，延迟可能翻倍
- **有标签数据时不如凸组合（Convex Combination）**：当有少量标注数据可用于调参时，基于归一化分数的加权融合方法通常效果更好

---

### 典型应用场景

- **混合检索（Hybrid Search）**：融合 BM25 关键词检索 + 向量语义检索的结果，是 RAG 系统中最常见的用法
- **RAG-Fusion**：用 LLM 生成多个子查询，分别检索后用 RRF 融合，提升召回覆盖度
- **多模态检索**：融合文本、视觉、音频等不同模态的检索结果
- **多模型集成**：融合多个不同模型（如 5 个 Transformer）的排序结果，提升实体归一化等任务的准确率

---

### 工程实现

RRF 已被主流搜索引擎和向量数据库原生支持：

- **Elasticsearch**：通过 `rrf` 查询语法支持，参数包括 `rank_constant`（即 k）和 `window_size`
- **Azure AI Search**：在混合查询和多向量查询中自动使用 RRF
- **Milvus**：通过 `RRFRanker` 类支持混合搜索的重排序

---

### 总结

RRF 是一种简单而有效的"投票式"融合策略——**在多个检索列表中排名都靠前的文档，最终排名也会靠前**。
它特别适合需要快速部署、缺乏标注数据、或需要融合异构检索系统的场景。
当有标注数据可用时，可以考虑更精细的分数加权融合方法来进一步提升效果。
"""
